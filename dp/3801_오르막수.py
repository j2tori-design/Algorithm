# 3801. 오르막수
# [핵심] dp[k][i] = 길이가 k이고 마지막 자리가 i인 오르막수의 개수. 앞자리 j는 i 이하면 되므로 dp[k][i] = dp[k-1][0] + ... + dp[k-1][i].
# [주의] 같은 숫자가 이어져도 오르막수로 치므로 j의 범위가 i를 포함한다 (range(i+1)).
# [주의] 수가 매우 커지므로 더할 때마다 10007로 나눈 나머지만 남기고, 마지막 합에도 한 번 더 나머지를 취한다.
N = int(input())
dp = [[0]*10 for _ in range(N+1)]
count = 0

def UpCount(N):
    # 길이 1짜리는 0 ~ 9 각각 1개
    for j in range(10):
        dp[1][j] = 1

    for k in range(2, N+1):
        for i in range(10):
            for j in range(i+1):
                dp[k][i] += dp[k-1][j]
                dp[k][i] %= 10007

    count = sum(dp[N]) % 10007
    return count
    
print(UpCount(N))

