# 3301. 거스름돈
# [핵심] 큰 단위부터 최대한 많이 쓰는 그리디.
# [주의] 이 방법이 최적인 이유는 각 단위가 더 작은 단위의 배수이기 때문이다. 배수 관계가 아니면 (예: 1·3·4원으로 6원 만들기) 그리디가 틀리고 DP가 필요하다.
# [주의] 변수 이름 list가 내장 list()를 가린다.
def Money(n):
    num = 0
    list = [50000, 10000, 5000, 1000, 500, 100, 50, 10]
    for i in list:
        num += n // i
        n = n % i
    return num

n = int(input())
print(Money(n))
